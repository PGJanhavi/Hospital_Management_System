    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
         String doctorName = dname.getText();
                //Load Driver
                try{
                    DefaultTableModel model = (DefaultTableModel)Table.getModel();
                    
                Class.forName("com.mysql.cj.jdbc.Driver");
        //Create connection
                Connection con = DriverManager.getConnection("jdbc:mysql://127.0.0.1:3306/Hospital","root","Janhavi@8050");
                String query = "SELECT * FROM doctor WHERE id = ?";
                PreparedStatement pstmt = con.prepareStatement(query);
                pstmt.setString(1,doctorName);
                ResultSet rs = pstmt.executeQuery();
                while(rs.next())
                {
                    int did = rs.getInt("id");
                    String doctorId = Integer.toString(did);
                    String dname = rs.getString("name");
                    String dDepartment = rs.getString("department");
                    String row[] = {doctorId, dname, dDepartment};
                    model.addRow(row);
                }
                con.close();
                } catch(Exception e)
                {
                    JOptionPane.showMessageDialog(this,e);
                }


    }//GEN-LAST:event_jButton1ActionPerformed

